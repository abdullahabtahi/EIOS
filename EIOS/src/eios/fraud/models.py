"""Domain entities and Pydantic v2 schemas for Partner Fraud Sentinel (Module B / Slice S3).

Authoritative References:
- docs/brief/fraud [BRIEF fraud]
- initial_plan.md §5.3 [BRIEF initial_plan.md]
- specs/009-partner-fraud/data-model.md
"""

from datetime import UTC, datetime
from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class DirectionalType(StrEnum):
    """Trading direction correlation type between two client accounts."""

    OPPOSITE = "OPPOSITE"
    MIRROR = "MIRROR"
    UNCORRELATED = "UNCORRELATED"


class FraudTypology(StrEnum):
    """Canonical partner fraud typologies per docs/brief/fraud."""

    OPPOSITE_TRADING_SYNDICATE = "OPPOSITE_TRADING_SYNDICATE"
    MIRROR_TRADING_RING = "MIRROR_TRADING_RING"
    BONUS_CPA_HARVESTING = "BONUS_CPA_HARVESTING"
    MULTI_TIER_COMMISSION_FRAUD = "MULTI_TIER_COMMISSION_FRAUD"
    CLIENT_RECYCLING = "CLIENT_RECYCLING"
    BOT_TRAFFIC_FUNNEL = "BOT_TRAFFIC_FUNNEL"


class TradingPairCorrelation(BaseModel):
    """Quantifies collusive trading relationship between two accounts referred by distinct affiliates."""

    model_config = ConfigDict(extra="forbid")

    pair_id: str = Field(..., description="Unique deterministic pair identifier")
    account_a: str = Field(..., description="First client account identifier")
    partner_a: str = Field(..., description="Affiliate ID referring account A")
    account_b: str = Field(..., description="Second client account identifier")
    partner_b: str = Field(..., description="Affiliate ID referring account B")
    symbol: str = Field(..., description="Financial instrument traded (e.g. EURUSD)")
    co_occurrence_count: int = Field(
        ..., ge=1, description="Number of correlated trade events observed"
    )
    timing_correlation_pct: float = Field(
        ..., ge=0.0, le=100.0, description="Percentage of trades executed within 15s window"
    )
    directional_type: DirectionalType = Field(
        ..., description="Directional alignment (OPPOSITE/MIRROR/UNCORRELATED)"
    )
    size_symmetry_score: float = Field(
        ..., ge=0.0, le=1.0, description="Volume symmetry between the two accounts"
    )
    combined_net_pl_usd: float = Field(
        ..., description="Combined net trading profit/loss across the pair"
    )
    total_commission_extracted_usd: float = Field(
        ..., ge=0.0, description="Total partner commissions generated by the pair"
    )
    zero_sum_ratio: float = Field(
        ..., ge=0.0, le=1.0, description="Measure of zero-sum volume extraction"
    )
    collusion_confidence: float = Field(
        ..., ge=0.0, le=1.0, description="Composite collusion probability"
    )


class ReferralRingNode(BaseModel):
    """Represents a node in the multi-tier affiliate hierarchy."""

    model_config = ConfigDict(extra="forbid")

    partner_id: str = Field(..., description="Partner identifier")
    parent_partner_id: str | None = Field(
        default=None, description="Parent affiliate ID in hierarchy"
    )
    tier_level: int = Field(
        ..., ge=1, le=3, description="Depth in hierarchy (1=Master, 2=Sub, 3=Sub-sub)"
    )
    direct_referred_clients: int = Field(
        ..., ge=0, description="Count of directly referred clients"
    )
    direct_commission_usd: float = Field(..., ge=0.0, description="Direct commission earned")
    sub_affiliate_count: int = Field(..., ge=0, description="Number of direct sub-affiliates")
    is_root_master: bool = Field(default=False, description="True if top-level root master partner")


class RingAttribution(BaseModel):
    """Multi-tier sub-affiliate network ring and root master attribution summary."""

    model_config = ConfigDict(extra="forbid")

    ring_id: str = Field(..., description="Unique deterministic ring identifier")
    master_partner_id: str = Field(..., description="Root master partner ID")
    total_affiliated_partners: int = Field(..., ge=1, description="Total partner nodes in ring")
    total_referred_clients: int = Field(..., ge=0, description="Total referred clients across ring")
    hierarchy_depth: int = Field(..., ge=1, le=3, description="Maximum tree depth (1 to 3)")
    total_ring_commission_usd: float = Field(
        ..., ge=0.0, description="Total commission earned across the ring"
    )
    flagged_abuse_commission_usd: float = Field(
        ..., ge=0.0, description="Illicit commission exposed to clawback"
    )
    ring_risk_score: float = Field(
        ..., ge=0.0, le=1.0, description="Composite ring fraud risk score"
    )
    top_violating_sub_partners: list[str] = Field(
        default_factory=list, description="List of sub-affiliates with highest violations"
    )
    nodes: list[ReferralRingNode] = Field(
        default_factory=list, description="Tree nodes participating in ring"
    )


class BonusAbuseProfile(BaseModel):
    """Summarizes deposit-to-withdrawal velocity and bonus harvesting behavior per partner."""

    model_config = ConfigDict(extra="forbid")

    partner_id: str = Field(..., description="Partner identifier")
    total_referred_clients: int = Field(..., ge=0, description="Total clients referred")
    fast_withdrawal_count_72h: int = Field(
        ..., ge=0, description="Clients withdrawing within 72h of deposit"
    )
    micro_trade_only_count: int = Field(..., ge=0, description="Clients with <= 2 micro-lot trades")
    median_holding_duration_hours: float = Field(
        ..., ge=0.0, description="Median position holding duration in hours"
    )
    turnover_to_deposit_ratio: float = Field(
        ..., ge=0.0, description="Total volume USD / total deposited USD"
    )
    cpa_bounty_collected_usd: float = Field(..., ge=0.0, description="Total CPA bounties collected")
    client_quality_index: float = Field(
        ..., ge=0.0, le=1.0, description="Client Quality Index [0.0 = pure abuse, 1.0 = organic]"
    )
    abuse_probability: float = Field(
        ..., ge=0.0, le=1.0, description="Probability of systematic bonus harvesting"
    )
    status: Literal["NORMAL", "MONITORING", "HIGH_BONUS_ABUSE_RISK"] = Field(
        ..., description="Partner quality status"
    )


class RecyclingCluster(BaseModel):
    """Captures multi-affiliate promotion recycling linked via Layer 1 Identity Tokens."""

    model_config = ConfigDict(extra="forbid")

    identity_cluster_key: str = Field(..., description="Pseudonymized key tok_id_cluster_<hex16>")
    linked_client_ids: list[str] = Field(
        ..., description="Client account IDs linked to identity token"
    )
    distinct_partner_ids: list[str] = Field(
        ..., description="Distinct partner IDs referring this cluster"
    )
    total_promotions_harvested_usd: float = Field(
        ..., ge=0.0, description="Total promotional bonus collected"
    )
    first_seen: datetime = Field(..., description="First activity timestamp")
    last_seen: datetime = Field(..., description="Last activity timestamp")
    syndicate_risk_score: float = Field(
        ..., ge=0.0, le=1.0, description="Recycling syndicate risk score"
    )


class TrafficAnomalySignal(BaseModel):
    """Measures unnatural conversion anomalies and bot-driven funnels."""

    model_config = ConfigDict(extra="forbid")

    partner_id: str = Field(..., description="Partner identifier")
    click_count: int = Field(..., ge=0, description="Total marketing clicks recorded")
    registration_count: int = Field(..., ge=0, description="Total registrations recorded")
    ftd_count: int = Field(..., ge=0, description="First-time deposits recorded")
    click_to_signup_rate: float = Field(
        ..., ge=0.0, le=1.0, description="Click to registration conversion rate"
    )
    signup_to_deposit_rate: float = Field(
        ..., ge=0.0, le=1.0, description="Signup to deposit conversion rate"
    )
    peer_cohort_mean_conversion: float = Field(
        ..., ge=0.0, le=1.0, description="Benchmark mean conversion rate for peer cohort"
    )
    p_value: float = Field(
        ..., ge=0.0, le=1.0, description="Statistical p-value against peer distribution"
    )
    bot_traffic_probability: float = Field(
        ..., ge=0.0, le=1.0, description="Estimated probability traffic is bot/fake"
    )
    anomaly_flag: bool = Field(
        ..., description="True if conversion deviates significantly (>3.0 sigma)"
    )


class PartnerFraudCase(BaseModel):
    """The comprehensive investigation dossier entity."""

    model_config = ConfigDict(extra="forbid")

    case_id: str = Field(..., description="Unique case reference CASE-FRAUD-<ID>")
    partner_id: str = Field(..., description="Target partner under investigation")
    master_partner_id: str | None = Field(
        default=None, description="Root master partner if sub-affiliate"
    )
    primary_typology: FraudTypology = Field(..., description="Primary suspected fraud typology")
    fraud_risk_score: float = Field(
        ..., ge=0.0, le=1.0, description="Composite fraud severity score"
    )
    total_exposure_usd: float = Field(
        ..., ge=0.0, description="Estimated financial exposure / illicit commission extracted"
    )
    confidence_level: Literal["LOW", "MEDIUM", "HIGH", "CRITICAL"] = Field(
        ..., description="Confidence level"
    )
    implicated_accounts: list[str] = Field(
        default_factory=list, description="Referred accounts involved"
    )
    evidence_refs: list[str] = Field(
        default_factory=list, description="Pointers to trade/comms data products"
    )
    narrative_summary: str = Field(..., description="Sanitized compliance briefing")
    recommended_action: Literal[
        "ClawbackCommission", "SuspendPartner", "AdjustPartnerTier", "ReviewAudit"
    ] = Field(..., description="Governed action intent recommendation")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC), description="Case creation timestamp"
    )
    status: Literal["OPEN", "UNDER_REVIEW", "ACTIONED", "DISMISSED"] = Field(
        default="OPEN", description="Investigation status"
    )
